-- Initial schema for Personal University.
-- Keep column types compatible with the current FastAPI response and query code.
-- Apply through Supabase CLI migrations; do not paste into the remote SQL Editor.

create table if not exists public.courses (
    id bigint generated by default as identity primary key,
    title text not null,
    topic text not null,
    difficulty text not null,
    description text
);

create table if not exists public.modules (
    id bigint generated by default as identity primary key,
    course_id bigint not null references public.courses(id),
    title text not null,
    summary text,
    order_index integer not null
);

create table if not exists public.lessons (
    id bigint generated by default as identity primary key,
    module_id bigint not null references public.modules(id),
    title text not null,
    content text not null,
    completed integer not null default 0 check (completed in (0, 1)),
    order_index integer not null
);

create table if not exists public.quizzes (
    id bigint generated by default as identity primary key,
    lesson_id bigint not null references public.lessons(id),
    question text not null,
    options_json text not null,
    correct_answer text not null,
    explanation text
);

create table if not exists public.chat_messages (
    id bigint generated by default as identity primary key,
    mode text not null,
    lesson_id bigint,
    thread_id text,
    role text not null,
    content text not null,
    created_at timestamptz not null default now()
);

create index if not exists idx_modules_course_order
    on public.modules(course_id, order_index);
create index if not exists idx_lessons_module_order
    on public.lessons(module_id, order_index);
create index if not exists idx_quizzes_lesson
    on public.quizzes(lesson_id);
create index if not exists idx_chat_messages_mode_id
    on public.chat_messages(mode, id);
create index if not exists idx_chat_messages_mode_lesson_id
    on public.chat_messages(mode, lesson_id, id);
create index if not exists idx_chat_messages_mode_thread_id
    on public.chat_messages(mode, thread_id, id);

-- The FastAPI backend will connect server-side with DATABASE_URL. The Android
-- app must not connect directly to these tables using an anon/publishable key.
-- Enable RLS and remove client-role privileges as defense in depth.
alter table public.courses enable row level security;
alter table public.modules enable row level security;
alter table public.lessons enable row level security;
alter table public.quizzes enable row level security;
alter table public.chat_messages enable row level security;

revoke all on table public.courses, public.modules, public.lessons,
    public.quizzes, public.chat_messages from anon, authenticated;
